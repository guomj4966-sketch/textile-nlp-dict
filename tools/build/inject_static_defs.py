for lk in lex['layers'].keys():
    ld = lex['layers'][lk]
    terms = ld.get('terms', {})
    t, d = count_defs(terms)
    total_all += t
    def_all += d
    pct = d / t * 100 if t else 0
    print(f'  {lk:35s} {d:>4}/{t:>4} ({pct:>4.0f}%)  {ld["description"]}')

pct_all = def_all / total_all * 100 if total_all else 0
print(f'  {"TOTAL":35s} {def_all:>4}/{total_all:>4} ({pct_all:.0f}%)')

