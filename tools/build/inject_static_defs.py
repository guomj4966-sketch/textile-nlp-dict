def count_defs(obj):
    total = set()
    with_def = set()

    def walk(o, cur_def=''):
        if isinstance(o, str) and len(o) >= 2:
            total.add(o)
            if cur_def:
                with_def.add(o)
        elif isinstance(o, list):
            for i in o:
                walk(i, cur_def)
        elif isinstance(o, dict):
            ld = o.get('definition', cur_def)
            for k, v in o.items():
                if k in META_KEYS:
                    continue
                if len(k) >= 2:
                    total.add(k)
                    if ld:
                        with_def.add(k)
                walk(v, ld)

    walk(obj)
    return len(total), len(with_def)

print()
