updated = 0

for layer_key, layer_data in lex['layers'].items():
    terms = layer_data.get('terms', {})
    if not isinstance(terms, dict):
        continue

    for cat_key, cat_val in list(terms.items()):
        # 情况1: 分类值是list, 如 绿色合规: [低碳, 废弃, ...]
        if isinstance(cat_val, list) and any(
            isinstance(item, str) and item in STATIC_DEFS for item in cat_val
        ):
            for term in cat_val:
                if isinstance(term, str) and term in STATIC_DEFS:
                    if term not in terms:
                        terms[term] = {'definition': STATIC_DEFS[term]}
                        updated += 1

        # 情况2: 分类值是dict, 如 中央部委: {国务院: {...}, ...}
        elif isinstance(cat_val, dict):
            for sub_key, sub_val in list(cat_val.items()):
                if sub_key in STATIC_DEFS and isinstance(sub_val, dict):
                    if 'definition' not in sub_val:
                        sub_val['definition'] = STATIC_DEFS[sub_key]
                        updated += 1

print(f'注入: {updated} 条')

